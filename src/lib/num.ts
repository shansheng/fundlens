/// 数值展示口径（供 GainLossBadge / TrendChip 等涨跌展示组件共用）。
///
/// **负零问题**：浮点运算会让「本该是 0」的值变成 `-1e-10`（如 `a - a` 经过一轮加减、
/// 或除不尽后回乘）。若不归一，同一组件里**颜色判定**与**文本格式化**会各走各的：
/// - 颜色按 `v < 0` → 判为「跌」（绿）
/// - 文本按 `(v * 100).toFixed(2)` → 得到 `-0.00%`
///
/// 结果就是自相矛盾的「绿色 −0.00%」。把阈值与归一函数收到一处，
/// 保证颜色、图标、正负号、小数位全部取自**同一个**判定结果。

/// 视为「无涨跌 / 无盈亏」的阈值。低于此绝对值一律按 0 处理。
export const FLAT_EPSILON = 1e-9;

/// 负零归一：`|v| < FLAT_EPSILON` 收敛到 `0`，其余原样返回。
///
/// 返回的是字面量 `0`（正零），因此后续 `toFixed` / `toLocaleString` / 比较
/// 都不会再产生 `-0.00` 或误判方向。
export function normalizeFlat(v: number): number {
  return Math.abs(v) < FLAT_EPSILON ? 0 : v;
}
